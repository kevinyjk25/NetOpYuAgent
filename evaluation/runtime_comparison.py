async def _tamper_evident_audit(root: Path) -> ScenarioObservation:
    # A generic append-only-looking list has no integrity verifier.
    generic_log = [{"event": "approved", "actor": "operator"}]
    generic_log[0]["actor"] = "tampered"
    direct_detected = False

    _reset_lan_state()
    runtime_path = root / "audit.sqlite"
    runtime = NetworkRuntime(runtime_path)
    prepared = await _prepare(runtime, "grant_user_access", {
        "user_id": "erin", "reason": "audit tamper test",
    })
    await _execute(runtime, prepared)
    plan_id = prepared["plan"]["plan_id"]
    before = runtime.audit(plan_id)
    with sqlite3.connect(runtime_path) as db:
        db.execute(
            "UPDATE plan_events SET payload_json=? WHERE event_id=("
            "SELECT MIN(event_id) FROM plan_events WHERE plan_id=?)",
            ('{"tampered":true}', plan_id),
        )
        db.commit()
    after = runtime.audit(plan_id)
    runtime_ok = before["ok"] is True and after["ok"] is False and bool(after["errors"])
    return ScenarioObservation(
        "tamper-evident-audit", "evidence_integrity", "审计防篡改", "Tamper-evident audit",
        "修改历史事件后，审计验证必须失败并定位损坏。",
        _observation(direct_detected, "undetected", 1,
                     "Generic record mutation has no domain event-chain verifier."),
        _observation(runtime_ok, "tamper_detected", 1,
                     f"Detected {len(after['errors'])} event-chain mismatch(es)."),
    )



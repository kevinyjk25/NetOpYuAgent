def read_history(path: str | Path) -> list[dict[str, Any]]:
    source = Path(path).expanduser()
    if not source.exists():
        return []
    values: list[dict[str, Any]] = []
    for line_number, line in enumerate(source.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        try:
            value = json.loads(line)
        except json.JSONDecodeError as error:
            raise ValueError(f"invalid Runtime A/B history line {line_number}: {error}") from error
        if not isinstance(value, dict) or not value.get("source_fingerprint"):
            raise ValueError(f"invalid Runtime A/B history record at line {line_number}")
        values.append(value)
    return values


def append_history(
    path: str | Path,
    snapshot: dict[str, Any],
) -> dict[str, Any]:
    destination = Path(path).expanduser().resolve()
    existing = read_history(destination)
    fingerprint = snapshot["source_fingerprint"]
    if any(item.get("source_fingerprint") == fingerprint for item in existing):
        return {
            "recorded": False,
            "reason": "implementation fingerprint already measured",
            "unique_iterations": len({item["source_fingerprint"] for item in existing}),
        }
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(snapshot, ensure_ascii=False, sort_keys=True) + "\n")
    return {
        "recorded": True,
        "reason": "new implementation fingerprint",
        "unique_iterations": len({
            *[item["source_fingerprint"] for item in existing], fingerprint,
        }),
    }


def evaluate_trend(
    baseline: dict[str, Any],
    history: list[dict[str, Any]],
) -> dict[str, Any]:
    thresholds = baseline["thresholds"]
    required = int(thresholds["minimum_unique_iterations"])
    unique: list[dict[str, Any]] = []
    seen: set[str] = set()
    for item in reversed(history):
        fingerprint = str(item["source_fingerprint"])
        if fingerprint in seen:
            continue
        seen.add(fingerprint)
        unique.append(item)
        if len(unique) == required:
            break
    unique.reverse()
    if len(unique) < required:
        return {
            "status": "collecting",
            "unique_iterations": len(unique),
            "required_iterations": required,
            "reasons": [f"need {required - len(unique)} more unique implementation iteration(s)"],
        }

    runtime = baseline["runtime"]
    p50 = statistics.median(float(item["p50_ms"]) for item in unique)
    p95 = statistics.median(float(item["p95_ms"]) for item in unique)
    reasons: list[str] = []
    regressed = False
    if not all(bool(item.get("all_oracles_passed")) for item in unique):
        regressed = True
        reasons.append("at least one Runtime oracle failed")
    minimum_control = min(float(item["control_effectiveness_rate"]) for item in unique)
    minimum_valid = min(float(item["valid_completion_rate"]) for item in unique)
    if minimum_control < float(runtime["control_effectiveness_rate"]):
        regressed = True
        reasons.append("fault/risk control effectiveness fell below baseline")
    if minimum_valid < float(runtime["valid_completion_rate"]):
        regressed = True
        reasons.append("valid request completion fell below baseline")

    relative_limit = float(thresholds["latency_regression_relative"])
    absolute_limit = float(thresholds["latency_regression_absolute_ms"])
    for name, value in (("p50", p50), ("p95", p95)):
        reference = float(runtime[f"{name}_ms"])
        if value > reference * relative_limit and value - reference > absolute_limit:
            regressed = True
            reasons.append(
                f"median {name} latency regressed from {reference:.3f} ms to {value:.3f} ms"
            )
    if regressed:
        status = "regressed"
    else:
        improvement_ratio = float(thresholds["latency_improvement_relative"])
        improvement_absolute = float(thresholds["latency_improvement_absolute_ms"])
        faster = []
        for name, value in (("p50", p50), ("p95", p95)):
            reference = float(runtime[f"{name}_ms"])
            if value < reference * (1.0 - improvement_ratio) and reference - value > improvement_absolute:
                faster.append(name)
        more_controls = max(int(item["control_scenarios"]) for item in unique) > int(
            runtime["control_scenarios"]
        )
        if faster or more_controls:
            status = "improved"
            if faster:
                reasons.append("median latency materially improved: " + ", ".join(faster))
            if more_controls:
                reasons.append("more fault/risk controls are covered at 100%")
        else:
            status = "stable"
            reasons.append("functional coverage is preserved and latency remains within noise thresholds")
    return {
        "status": status,
        "unique_iterations": len(unique),
        "required_iterations": required,
        "window_fingerprints": [item["source_fingerprint"] for item in unique],
        "median": {"p50_ms": round(p50, 3), "p95_ms": round(p95, 3)},
        "reasons": reasons,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--iterations", type=int, default=20, help="local latency samples (1-500)")
    parser.add_argument(
        "--output-dir", default="artifacts/runtime-ab",
        help="directory for runtime-ab.json, runtime-ab.md and runtime-ab.html",
    )
    parser.add_argument("--stdout", action="store_true", help="print the full JSON report")
    parser.add_argument(
        "--baseline", default="data/runtime_ab_baseline.json",
        help="versioned comparison baseline",
    )
    parser.add_argument(
        "--history", default="artifacts/runtime-ab/history.jsonl",
        help="JSONL trend history; duplicate implementation fingerprints are ignored",
    )
    parser.add_argument("--record", action="store_true", help="record this unique implementation iteration")
    parser.add_argument("--label", default="", help="optional iteration label stored in history")
    args = parser.parse_args(argv)
    try:
        report = asyncio.run(run_benchmark(iterations=args.iterations))
        baseline = load_baseline(args.baseline)
        snapshot = _runtime_snapshot(report, label=args.label)
        record = append_history(args.history, snapshot) if args.record else {
            "recorded": False, "reason": "--record not requested",
        }
        history = read_history(args.history)
        report["trend"] = {
            **evaluate_trend(baseline, history),
            "record": record,
            "baseline_id": baseline["baseline_id"],
        }
        paths = write_report(report, args.output_dir)
    except Exception as error:
        print(json.dumps({"ok": False, "error": f"{type(error).__name__}: {error}"}, ensure_ascii=False))
        return 1
    print(json.dumps(report if args.stdout else _summary(report, paths), ensure_ascii=False, indent=2))
    return 0 if all(item[RUNTIME_NAME]["passed"] for item in report["scenarios"]) else 1


if __name__ == "__main__":
    raise SystemExit(main())

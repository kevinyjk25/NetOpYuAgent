def _metric(scenarios: list[ScenarioObservation], path: str, category: str) -> dict[str, Any]:
    selected = [item for item in scenarios if item.category == category]
    passed = sum(1 for item in selected if getattr(item, path).passed)
    total = len(selected)
    return {
        "metric_id": category,
        "label_zh": CATEGORY_LABELS[category][0],
        "label_en": CATEGORY_LABELS[category][1],
        "passed": passed,
        "total": total,
        "rate": round(100.0 * passed / total, 1) if total else None,
    }


def _percentile(values: list[float], quantile: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    position = (len(ordered) - 1) * quantile
    lower = math.floor(position)
    upper = math.ceil(position)
    if lower == upper:
        return ordered[lower]
    return ordered[lower] + (ordered[upper] - ordered[lower]) * (position - lower)


async def _latency_campaign(root: Path, iterations: int) -> dict[str, Any]:
    arguments = {"user_id": "erin", "reason": "latency benchmark"}
    direct_values: list[float] = []
    runtime_values: list[float] = []
    runtime = NetworkRuntime(root / "latency.sqlite")
    # Warm imports, SQLite schema and tool store before measuring both paths.
    _reset_lan_state()
    await _direct_call("lan", "grant_user_access", arguments)
    _reset_lan_state()
    warm = await _prepare(runtime, "grant_user_access", arguments)
    await _execute(runtime, warm)
    for _ in range(iterations):
        _reset_lan_state()
        started = time.perf_counter_ns()
        direct = await _direct_call("lan", "grant_user_access", arguments)
        direct_values.append((time.perf_counter_ns() - started) / 1_000_000)
        if direct.error is not None:
            raise RuntimeError(f"direct latency trial failed: {direct.error}")

        _reset_lan_state()
        started = time.perf_counter_ns()
        prepared = await _prepare(runtime, "grant_user_access", arguments)
        outcome = await _execute(runtime, prepared)
        runtime_values.append((time.perf_counter_ns() - started) / 1_000_000)
        if outcome.state != PlanState.VERIFIED_SUCCESS:
            raise RuntimeError(f"runtime latency trial failed: {outcome.state.value}")

    def summary(values: list[float]) -> dict[str, Any]:
        return {
            "samples": len(values),
            "p50_ms": round(_percentile(values, 0.50), 3),
            "p95_ms": round(_percentile(values, 0.95), 3),
            "mean_ms": round(statistics.fmean(values), 3),
            "min_ms": round(min(values), 3),
            "max_ms": round(max(values), 3),
        }

    baseline = summary(direct_values)
    guarded = summary(runtime_values)
    guarded["p50_overhead_ms"] = round(guarded["p50_ms"] - baseline["p50_ms"], 3)
    guarded["p95_overhead_ms"] = round(guarded["p95_ms"] - baseline["p95_ms"], 3)
    guarded["p50_factor"] = round(guarded["p50_ms"] / max(baseline["p50_ms"], 0.001), 2)
    return {
        "unit": "milliseconds",
        "approval_wait_excluded": True,
        "provider": "profile-mock",
        BASELINE_NAME: baseline,
        RUNTIME_NAME: guarded,
    }



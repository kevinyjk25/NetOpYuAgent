def _json_type_ok(name: str, value: Any) -> bool:
    integer = {
        "flows", "grace_period_s", "length", "lines", "minutes", "offset",
        "range_minutes", "route_type", "top_n", "vlan_id", "vni",
    }
    boolean = {"dry_run", "force", "graceful", "rolling"}
    arrays = {"config_lines", "device_ids"}
    objects = {"changes"}
    if name in integer:
        return isinstance(value, int) and not isinstance(value, bool)
    if name in boolean:
        return isinstance(value, bool)
    if name in arrays:
        return isinstance(value, list)
    if name in objects:
        return isinstance(value, dict)
    return isinstance(value, str)


def _harness_schema_error(metadata: dict[str, Any], arguments: dict[str, Any]) -> str | None:
    """Mirror the JSON-schema boundary generated by the DSH plugin."""
    definitions = metadata.get("parameters") or {}
    unknown = sorted(set(arguments) - set(definitions))
    if unknown:
        return "additional properties are not allowed: " + ", ".join(unknown)
    required = set(metadata.get("required") or ())
    missing = sorted(
        name for name in required
        if name not in arguments or arguments[name] is None or arguments[name] == ""
    )
    if missing:
        return "missing required properties: " + ", ".join(missing)
    invalid = sorted(
        name for name, value in arguments.items()
        if name in definitions and not _json_type_ok(name, value)
    )
    if invalid:
        return "invalid JSON-schema types: " + ", ".join(invalid)
    return None


async def _direct_call(
    profile: str,
    tool_name: str,
    arguments: dict[str, Any],
    *,
    approved: bool = True,
    configure: Callable[[BackendSession], None] | None = None,
) -> DirectResult:
    """Reference DSH-only path: schema + generic approval + direct provider."""
    backend = await open_backend(profile)
    calls = 0
    try:
        metadata = backend.metadata.get(tool_name)
        tool = backend.callables.get(tool_name)
        if metadata is None or tool is None:
            return DirectResult(False, None, "unknown tool", 0)
        schema_error = _harness_schema_error(metadata, arguments)
        if schema_error:
            return DirectResult(False, None, schema_error, 0)
        mutating = bool(metadata.get("hitl")) or metadata.get("action_type") != "read_only"
        if mutating and not approved:
            return DirectResult(False, None, "generic approval rejected", 0)
        if configure is not None:
            configure(backend)
            tool = backend.callables[tool_name]
        calls += 1
        try:
            value = await tool(dict(arguments))
        except Exception as error:
            return DirectResult(True, None, f"{type(error).__name__}: {error}", calls)
        rendered = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)
        return DirectResult(True, rendered, None, calls)
    finally:
        await backend.close()


async def _prepare(
    runtime: NetworkRuntime,
    tool_name: str,
    arguments: dict[str, Any],
) -> dict[str, Any]:
    contract = L0_SKILLS.for_tool("lan", tool_name)
    return await runtime.prepare(
        "lan", tool_name, arguments,
        l0_skill_id=contract.skill_id if contract is not None else None,
    )


async def _execute(runtime: NetworkRuntime, prepared: dict[str, Any]) -> Any:
    plan = prepared["plan"]
    return await runtime.execute(
        plan_id=plan["plan_id"],
        plan_hash=plan["plan_hash"],
        execution_nonce=prepared["execution_nonce"],
        approval_request_id="runtime-ab-approval",
        approval_actor="runtime-ab-operator",
        allow_destructive=True,
    )



@contextmanager
def _benchmark_environment(root: Path) -> Iterator[None]:
    names = {
        "NETOPYU_BACKEND": "mock",
        "NETOPYU_DSH_BACKEND": "mock",
        "NETOPYU_DSH_TOOL_RESULT_STORE": str(root / "tool-results.sqlite"),
        "NETOPYU_TOOL_RESULT_STORE": str(root / "tool-results.sqlite"),
    }
    previous = {name: os.environ.get(name) for name in names}
    os.environ.update(names)
    try:
        yield
    finally:
        for name, value in previous.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value



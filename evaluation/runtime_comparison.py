def source_fingerprint(project_root: str | Path | None = None) -> str:
    """Hash only the execution implementation, excluding docs/tests/evaluation."""
    root = (
        Path(project_root).expanduser().resolve()
        if project_root is not None
        else Path(__file__).resolve().parents[1]
    )
    patterns = (
        "dsh_adapter/*.py",
        "dsh-plugin-netopyu/src/*.js",
        "effect_runtime/*.py",
        "network_runtime/*.py",
        "network_provider/*.py",
        "service_layer/*.py",
    )
    files = sorted({path for pattern in patterns for path in root.glob(pattern) if path.is_file()})
    digest = hashlib.sha256()
    for path in files:
        digest.update(path.relative_to(root).as_posix().encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return "sha256:" + digest.hexdigest()


def load_baseline(path: str | Path) -> dict[str, Any]:
    value = json.loads(Path(path).expanduser().read_text(encoding="utf-8"))
    if value.get("schema") != BASELINE_SCHEMA:
        raise ValueError(f"unsupported Runtime A/B baseline schema: {value.get('schema')!r}")
    runtime = value.get("runtime") or {}
    thresholds = value.get("thresholds") or {}
    required = {
        "control_effectiveness_rate", "valid_completion_rate", "control_scenarios",
        "p50_ms", "p95_ms",
    }
    missing = sorted(required - set(runtime))
    if missing:
        raise ValueError("Runtime A/B baseline missing fields: " + ", ".join(missing))
    if int(thresholds.get("minimum_unique_iterations", 0)) < 2:
        raise ValueError("minimum_unique_iterations must be at least 2")
    return value



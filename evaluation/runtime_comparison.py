async def _provider_drift(root: Path) -> ScenarioObservation:
    arguments = {"user_id": "erin", "reason": "provider binding test"}
    _reset_lan_state()

    def drift_direct(backend: BackendSession) -> None:
        backend.metadata["grant_user_access"] = {
            **backend.metadata["grant_user_access"],
            "provider_identity": "changed-after-generic-approval",
        }

    direct = await _direct_call("lan", "grant_user_access", arguments, configure=drift_direct)
    direct_safe = not direct.accepted and direct.provider_calls == 0

    _reset_lan_state()
    opens = 0
    writes = 0

    async def factory(profile: str) -> BackendSession:
        nonlocal opens, writes
        backend = await open_backend(profile)
        opens += 1
        original = backend.callables["grant_user_access"]

        async def counted(values: dict[str, Any]) -> Any:
            nonlocal writes
            writes += 1
            return await original(values)

        backend.callables["grant_user_access"] = counted
        if opens >= 2:
            backend.metadata["grant_user_access"] = {
                **backend.metadata["grant_user_access"],
                "provider_identity": "changed-after-runtime-approval",
            }
        return backend

    runtime = NetworkRuntime(root / "provider-drift.sqlite", backend_factory=factory)
    prepared = await _prepare(runtime, "grant_user_access", arguments)
    blocked = False
    detail = ""
    try:
        await _execute(runtime, prepared)
    except PlanIntegrityError as error:
        blocked = writes == 0
        detail = str(error)
    return ScenarioObservation(
        "provider-contract-drift", "approval_binding", "审批后 Provider 漂移",
        "Provider drift after approval",
        "审批后 Provider 身份或契约变化时不得发送写操作。",
        _observation(direct_safe, "blocked" if direct_safe else "write_sent_to_changed_provider",
                     direct.provider_calls, direct.error or "No provider-contract binding."),
        _observation(blocked, "blocked", writes, detail),
    )


